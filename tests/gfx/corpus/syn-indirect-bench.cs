// Cell c of the 64x64 grid: a 2x2 px quad centered in the 4x4 px cell
// (256x256 target). Cell NDC size 0.03125; quad 0.015625; inset 0.0078125.
void bench_quad(uint firstVertex, uint cell, vec4 col)
{
  float x0 = -1.0 + float(cell % 64u) * 0.03125 + 0.0078125;
  float y0 = -1.0 + float(cell / 64u) * 0.03125 + 0.0078125;
  float x1 = x0 + 0.015625;
  float y1 = y0 + 0.015625;
  geo_position_out[firstVertex + 0u] = vec4(x0, y0, 0.0, 1.0);
  geo_position_out[firstVertex + 1u] = vec4(x1, y0, 0.0, 1.0);
  geo_position_out[firstVertex + 2u] = vec4(x1, y1, 0.0, 1.0);
  geo_position_out[firstVertex + 3u] = vec4(x0, y0, 0.0, 1.0);
  geo_position_out[firstVertex + 4u] = vec4(x1, y1, 0.0, 1.0);
  geo_position_out[firstVertex + 5u] = vec4(x0, y1, 0.0, 1.0);
  for(uint v = 0u; v < 6u; v++)
    geo_color_out[firstVertex + v] = col;
}

void main()
{
  if(PASSINDEX == 0)
  {
    if(gl_GlobalInvocationID.x != 0u)
      return;
    uint n = uint(clamp(alive, 0, 4096));
    args.xyz[0] = (n + 63u) / 64u;
    args.xyz[1] = 1u;
    args.xyz[2] = 1u;
    args.xyz[3] = 0u;
    geo_indirect_count = n;

    bool p = (poison != 0);
    for(uint j = n; j < 4096u; j++)
    {
      geo_indirect[j].vertexCount   = p ? 6u : 0u;
      geo_indirect[j].instanceCount = p ? 1u : 0u;
      geo_indirect[j].firstVertex   = p ? 24576u + 6u * j : 0u;
      geo_indirect[j].baseVertex    = 0;
      geo_indirect[j].firstInstance = 0u;
    }
    return;
  }

  if(PASSINDEX == 1)
  {
    // One thread per alive slot; self-bound for the CPU-ceiling fallback.
    uint t = gl_GlobalInvocationID.x;
    if(t >= geo_indirect_count)
      return;
    geo_indirect[t].vertexCount   = 6u;
    geo_indirect[t].instanceCount = 1u;
    geo_indirect[t].firstVertex   = 6u * t;
    geo_indirect[t].baseVertex    = 0;
    geo_indirect[t].firstInstance = 0u;
    return;
  }

  // PER_VERTEX: the whole vertex buffer is COMPUTE-GENERATED, every frame.
  uint v = gl_GlobalInvocationID.x;
  if(v >= 49152u)
    return;
  uint q = v / 6u;
  if(q < 4096u)
    bench_quad(v - (v % 6u), q, vec4(1.0, 0.0, 0.0, 1.0));
  else
    bench_quad(v - (v % 6u), q - 4096u, vec4(0.0, 0.0, 1.0, 1.0));
}
